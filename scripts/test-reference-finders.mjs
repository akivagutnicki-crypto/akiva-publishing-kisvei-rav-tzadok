import assert from 'node:assert/strict';
import { linkCitations } from './citations.mjs';
const refs = html => [...linkCitations(html).matchAll(/data-ref="([^"]+)"/g)].map(m => m[1].replace(/&amp;/g, '&'));
const has = (html, ref) => assert.ok(refs(html).includes(ref), `${html} -> ${refs(html).join(' | ')} (wanted ${ref})`);
has('(Zohar III, 73a)', 'Zohar, Achrei Mot 49:296-50:305');
has('the Zohar (Mishpatim 107b and Pinchas 227b)', 'Zohar, Mishpatim 3:248-258');
has('Raya Mehemna (Tzav 29b)', 'Zohar, Tzav 9:64-72');
// folios follow Sefaria's Vilna page markers (Rav Tzadok cites III 264a for Shema / Baruch Shem)
has('the Zohar (III, 264a)', 'Zohar, Vaetchanan 12:75-14:87');
has('Zohar III, 222b', 'Zohar, Pinchas 30:170-32:178');
has('Tikkun 21', 'Tikkunei Zohar 42b:2-63a:9');
has('Tikkunei Zohar 17b', 'Tikkunei Zohar 17b');
has('Tanchuma (Noach §3)', 'Midrash Tanchuma, Noach 3');
has('Midrash Tanchuma, Ki Tissa 34', 'Midrash Tanchuma, Ki Tisa 34');
has('Yerushalmi Peah (1:1)', 'Jerusalem Talmud Peah 1:1');
has('the Mishnah in Kelim (1:8–9)', 'Mishnah Kelim 1:8-9');
has('Rambam, Hilchos Ishus 8:5', 'Mishneh Torah, Marriage 8:5');
has('Laws of Rebels 1:2', 'Mishneh Torah, Rebels 1:2');
has('Pri Tzaddik, Vayeilech and Shabbos Shuvah §8', 'Peri Tzadik, Vayeilech and Shabbat Shuvah 8');
has('Kometz HaMinchah II §49', 'Kometz HaMinchah 2:49');
has('Mei HaShiloach (Vol. 1, Bereishis, s.v. x)', 'Mei HaShiloach, Volume I, Genesis, Bereshit');
has('Tanya, Likkutei Amarim ch. 39', 'Tanya, Part I; Likkutei Amarim 39');
has('<i>Zohar</i> III, 73a', 'Zohar, Achrei Mot 49:296-50:305');
assert.deepEqual(refs('Hilchos Sanhedrin 18:2'), ['Mishneh Torah, The Sanhedrin and the Penalties within Their Jurisdiction 18:2']);
console.log('reference finder checks passed');
// Hebrew-side citations
import { linkHebrewCitations } from './citations.mjs';
const heRefs = html => [...linkHebrewCitations(html).matchAll(/data-ref="([^"]+)"/g)].map(m => m[1]);
const heHas = (html, ref) => assert.ok(heRefs(html).includes(ref), `${html} -> ${heRefs(html).join(' | ')} (wanted ${ref})`);
heHas('(תהילים ס״ח:ל״ה)', 'Psalms 68:35');
heHas('כדאיתא בברכות ז׳ ע״ב', 'Berakhot 7b');
heHas('(יבמות ס״ב:)', 'Yevamot 62b');
heHas('בְּרָכוֹת דַּף מ״ג עַמּוּד ב׳', 'Berakhot 43b');
heHas('בזוה"ק (לך פד.)', 'Zohar, Lech Lecha 18:165-19:176');
heHas('תיקוני זוהר דף י״ז ע״ב', 'Tikkunei Zohar 17b');
heHas('הלכות תשובה פרק ג הלכה ד', 'Mishneh Torah, Repentance 3:4');
heHas('ספר חסידים סי\' רל"א', 'Sefer Chasidim 231');
heHas('אבות פ"ג מ"ד', 'Mishnah Avot 3:4');
heHas('<i>ישעיה</i> נ״ח י״ג', 'Isaiah 58:13');
assert.deepEqual(heRefs('שמואל א, כט'), []);   // chapter without a verse is not a verse citation
assert.deepEqual(heRefs('ויקרא אל משה שבת קודש'), []);
console.log('Hebrew citation checks passed');
